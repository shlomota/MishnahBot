/* Shared canvas drawing toolkit for Daily Mishnah explainer videos.
   This file is fixed, hand-written infrastructure - never regenerated by an
   LLM. Each day's actual scene content/drawing code (scN functions) is
   generated fresh and loaded alongside this file; it calls into these
   primitives plus the raw canvas context (X) directly for anything bespoke.

   Ported from a hand-built reference video (mishnah-shabbat-1) that proved
   out this exact technique: plain canvas, no animation library, a cheap
   "boil" wobble re-rolled a few times a second for a hand-drawn feel instead
   of true roughjs-style jitter. */

const W = 1280, H = 720;
const CREAM = '#f7eeda', INK = '#22304f', RED = '#d4543a', GOLD = '#e9b23a',
      OLIVE = '#6f8f4f', PLUM = '#8a5a8f', SKY = '#86b4cf', PAPER = '#efe0c2',
      BROWN = '#8d6243', GREEN = '#4f8a5c';

const HAND = '"Comic Sans MS", "Chalkboard SE", "Chalkboard", sans-serif';
const HEB = '"Arial Hebrew", "Arial Unicode MS", sans-serif';

let C, X;

/* ---------- tiny math/util ---------- */
const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
const lerp = (a, b, u) => a + (b - a) * u;
const ss = (a, b, v) => {
  const u = clamp((v - a) / (b - a), 0, 1);
  return u * u * (3 - 2 * u);
};
const easeOutCubic = (u) => 1 - Math.pow(1 - u, 3);
const easeOutBack = (u) => {
  const c = 1.9;
  return 1 + (c + 1) * Math.pow(u - 1, 3) + c * Math.pow(u - 1, 2);
};
const easeInCubic = (u) => u * u * u;

function hash(n) {
  const s = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return s - Math.floor(s);
}
/* "boil": hand-drawn wobble that re-rolls ~9x/second, so static things still
   read as hand-drawn without actually jittering every single frame. */
function boil(t, seed, amt = 2.2) {
  const k = Math.floor(t * 9) + seed * 97;
  return { x: (hash(k) - 0.5) * amt, y: (hash(k + 41) - 0.5) * amt, r: (hash(k + 83) - 0.5) * 0.012 };
}
function withBoil(t, seed, fn, amt) {
  const b = boil(t, seed, amt);
  X.save();
  X.translate(b.x, b.y);
  X.rotate(b.r);
  fn();
  X.restore();
}
const pop = (lt, t0, dur = 0.42) => (lt < t0 ? 0 : easeOutBack(clamp((lt - t0) / dur, 0, 1)));
const fade = (lt, t0, dur = 0.3) => clamp((lt - t0) / dur, 0, 1);

/* ---------- primitives ---------- */
function line(x1, y1, x2, y2, col = INK, w = 5) {
  X.strokeStyle = col;
  X.lineWidth = w;
  X.lineCap = 'round';
  X.beginPath();
  X.moveTo(x1, y1);
  X.lineTo(x2, y2);
  X.stroke();
}
function circle(x, y, r, fill, stroke = INK, w = 5) {
  X.beginPath();
  X.arc(x, y, r, 0, 7);
  if (fill) {
    X.fillStyle = fill;
    X.fill();
  }
  if (stroke) {
    X.strokeStyle = stroke;
    X.lineWidth = w;
    X.stroke();
  }
}
function rr(x, y, w, h, r, fill, stroke = INK, lw = 5) {
  X.beginPath();
  X.roundRect(x, y, w, h, r);
  if (fill) {
    X.fillStyle = fill;
    X.fill();
  }
  if (stroke) {
    X.strokeStyle = stroke;
    X.lineWidth = lw;
    X.stroke();
  }
}
function text(str, x, y, size, col = INK, opts = {}) {
  const fam = opts.heb ? HEB : HAND;
  X.font = `${opts.bold === false ? '' : 'bold '}${size}px ${fam}`;
  X.textAlign = opts.align || 'center';
  X.textBaseline = opts.baseline || 'middle';
  X.direction = opts.heb ? 'rtl' : 'ltr';
  if (opts.outline) {
    X.lineWidth = opts.outline;
    X.strokeStyle = opts.outlineCol || CREAM;
    X.lineJoin = 'round';
    X.strokeText(str, x, y);
  }
  X.fillStyle = col;
  X.fillText(str, x, y);
  X.direction = 'ltr';
}
function measure(str, size, heb) {
  X.font = `bold ${size}px ${heb ? HEB : HAND}`;
  return X.measureText(str).width;
}

/* rough hand-drawn rectangle */
function sketchRect(x, y, w, h, t, seed, fill, stroke = INK, lw = 5) {
  const j = (s) => (hash(Math.floor(t * 9) + seed * 13 + s) - 0.5) * 4;
  X.beginPath();
  X.moveTo(x + j(1), y + j(2));
  X.lineTo(x + w + j(3), y + j(4));
  X.lineTo(x + w + j(5), y + h + j(6));
  X.lineTo(x + j(7), y + h + j(8));
  X.closePath();
  if (fill) {
    X.fillStyle = fill;
    X.fill();
  }
  if (stroke) {
    X.strokeStyle = stroke;
    X.lineWidth = lw;
    X.lineJoin = 'round';
    X.stroke();
  }
}

/* ---------- reusable characters/props ---------- */
function person(x, y, s, o = {}) {
  // y = ground line, s = scale (1 ~ 200px tall)
  X.save();
  X.translate(x, y);
  X.scale(s, s);
  const robe = o.robe || PLUM,
    skin = '#f0c9a0';
  X.beginPath();
  X.moveTo(-34, 0);
  X.lineTo(-24, -92);
  X.lineTo(24, -92);
  X.lineTo(34, 0);
  X.closePath();
  X.fillStyle = robe;
  X.fill();
  X.strokeStyle = INK;
  X.lineWidth = 5;
  X.lineJoin = 'round';
  X.stroke();
  if (o.patches) {
    X.fillStyle = 'rgba(0,0,0,.17)';
    X.fillRect(-20, -55, 18, 16);
    X.fillRect(6, -30, 14, 13);
  }
  const a1 = o.armL || [-26, -78, -52, -46],
    a2 = o.armR || [26, -78, 52, -46];
  line(a1[0], a1[1], a1[2], a1[3], INK, 7);
  line(a2[0], a2[1], a2[2], a2[3], INK, 7);
  circle(0, -116, 25, skin, INK, 5);
  X.beginPath();
  X.moveTo(-22, -110);
  X.quadraticCurveTo(0, o.longBeard ? -56 : -72, 22, -110);
  X.fillStyle = o.beard || '#5b4636';
  X.fill();
  X.strokeStyle = INK;
  X.lineWidth = 4;
  X.stroke();
  const ey = -122,
    sq = o.squint ? 0 : 1;
  if (sq) {
    circle(-9, ey, 3.4, INK, null);
    circle(9, ey, 3.4, INK, null);
  } else {
    line(-14, ey, -4, ey, INK, 4);
    line(4, ey, 14, ey, INK, 4);
  }
  if (o.brows) {
    line(-16, ey - 12, -3, ey - 7, INK, 4);
    line(3, ey - 7, 16, ey - 12, INK, 4);
  }
  X.beginPath();
  X.moveTo(-27, -128);
  X.quadraticCurveTo(0, -160, 27, -128);
  X.fillStyle = o.hat || '#d8d2c4';
  X.fill();
  X.strokeStyle = INK;
  X.lineWidth = 5;
  X.stroke();
  X.restore();
}

function basket(x, y, s, t, glow = 0) {
  X.save();
  X.translate(x, y);
  X.scale(s, s);
  if (glow > 0) {
    X.globalAlpha = glow * (0.5 + 0.5 * Math.sin(t * 14));
    circle(0, 0, 46, 'rgba(233,178,58,.55)', null);
    X.globalAlpha = 1;
  }
  X.beginPath();
  X.moveTo(-26, -14);
  X.lineTo(26, -14);
  X.lineTo(19, 20);
  X.lineTo(-19, 20);
  X.closePath();
  X.fillStyle = BROWN;
  X.fill();
  X.strokeStyle = INK;
  X.lineWidth = 5;
  X.lineJoin = 'round';
  X.stroke();
  line(-26, -14, 26, -14, INK, 5);
  X.beginPath();
  X.arc(0, -14, 20, Math.PI, 0);
  X.strokeStyle = INK;
  X.lineWidth = 5;
  X.stroke();
  X.restore();
}

function flame(x, y, s, t, col = GOLD) {
  const h = (18 + Math.sin(t * 13) * 3) * s;
  X.beginPath();
  X.moveTo(x, y);
  X.quadraticCurveTo(x + 10 * s, y - h * 0.6, x, y - h);
  X.quadraticCurveTo(x - 10 * s, y - h * 0.6, x, y);
  X.fillStyle = col;
  X.fill();
}

/* rubber stamp that thunks down onto the frame */
function stamp(str, x, y, lt, t0, col, size = 54, rot = -0.13, heb) {
  if (lt < t0) return;
  const u = clamp((lt - t0) / 0.3, 0, 1);
  const sc = lerp(2.4, 1, easeOutCubic(u)),
    al = ss(0, 0.5, u);
  X.save();
  X.translate(x, y);
  X.rotate(rot);
  X.scale(sc, sc);
  X.globalAlpha = al;
  const w = measure(str, size, heb) + 46;
  X.lineWidth = 6;
  X.strokeStyle = col;
  X.beginPath();
  X.roundRect(-w / 2, -size * 0.75, w, size * 1.5, 10);
  X.stroke();
  text(str, 0, 2, size, col, { heb });
  X.restore();
}

/* ---------- background + HUD (fixed chrome around every video) ---------- */
function background(t) {
  X.fillStyle = CREAM;
  X.fillRect(0, 0, W, H);
  X.fillStyle = 'rgba(120,95,60,.10)';
  for (let i = 0; i < 260; i++) X.fillRect(hash(i) * W, hash(i + 500) * H, 2, 2);
  X.save();
  const b = boil(t, 3, 2.6);
  X.translate(b.x, b.y);
  X.strokeStyle = 'rgba(34,48,79,.28)';
  X.lineWidth = 4;
  X.beginPath();
  X.roundRect(16, 16, W - 32, H - 32, 14);
  X.stroke();
  X.restore();
}

function hud(t, total, titleHeb) {
  const left = Math.min(60, Math.max(0, Math.ceil(total - t)));
  X.save();
  const b = boil(t, 11, 1.8);
  X.translate(W - 86 + b.x, 80 + b.y);
  circle(0, 0, 40, '#fff8e8', INK, 5);
  X.beginPath();
  X.arc(0, 0, 40, -Math.PI / 2, -Math.PI / 2 + 7 * clamp(t / total, 0, 1));
  X.strokeStyle = RED;
  X.lineWidth = 8;
  X.stroke();
  text(String(left), 0, 2, 34, INK);
  X.restore();
  X.save();
  X.globalAlpha = 0.85;
  text(titleHeb || '', 58, 70, 27, INK, { align: 'left', heb: true });
  X.restore();
  rr(40, H - 42, W - 80, 12, 6, '#e2d3b4', null);
  rr(40, H - 42, (W - 80) * clamp(t / total, 0, 1), 12, 6, OLIVE, null);
}
